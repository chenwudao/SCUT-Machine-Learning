# 提取特征：音高分布、节拍复杂度、速度
def extract_music_features(scores):
    features = []
    for score_id, content in scores.items():
        # 解析音高和节拍符号
        notes = content.split()
        pitch_counts = {}
        beat_changes = 0
        prev_beat = None
        speed = None
        
        for token in notes:
            if token.isdigit():  # 速度标记（如129）
                speed = int(token)
                continue
            # 分离音高和节拍符号（例如"6_", "1^"）
            pitch = ''.join([c for c in token if c.isalpha() or c.isdigit()])
            beat = '_' if '_' in token else 0
            # 统计音高
            pitch_counts[pitch] = pitch_counts.get(pitch, 0) + 1
            # 统计节拍变化
            if beat != prev_beat:
                beat_changes += 1
                prev_beat = beat
        
        # 归一化音高频率
        total_notes = len(notes)
        pitch_features = [pitch_counts.get(str(i), 0) / total_notes for i in range(1, 8)]
        # 组合特征：音高分布 + 节拍变化率 + 速度
        features.append(pitch_features + [beat_changes / total_notes, speed])
    
    return np.array(features)

